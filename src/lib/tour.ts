export type TourBlock = {
  /** 模擬畫面裡的區塊標題 */
  t: string;
  /** 一行說明 */
  d?: string;
  /** 底下的欄位小標籤 */
  fields?: string[];
  /** 這一步的落點：會被高亮，其餘區塊淡出 */
  hl?: boolean;
};

export type TourStep = {
  t: string;
  /** 顯示用的路由（可能含 [id] 這類參數） */
  where: string;
  /** 真的可以點過去的網址；帶參數的頁面就給不了，設 null */
  href: string | null;
  /** 說明，允許 <strong> */
  body: string;
  /** 提醒／陷阱，允許 <b> */
  note?: string;
  /** 模擬畫面上方的操作者標示 */
  role: string;
  blocks: TourBlock[];
};

export type TourRole = {
  key: string;
  who: string;
  what: string;
  rail: string;
  steps: TourStep[];
};


